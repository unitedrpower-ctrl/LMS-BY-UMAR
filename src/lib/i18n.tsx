export const getTranslation = (lang: string = 'en', key: string, defaultText?: string): string => {
  const code = (lang in TRANSLATIONS ? lang : 'en') as LanguageCode;
  return TRANSLATIONS[code]?.[key] || TRANSLATIONS.en[key] || defaultText || key;
};

export const translateStatus = (status: string, lang: LanguageCode = 'en'): string => {
  const s = status.toLowerCase().replace(/[\s_-]+/g, '');
  const map: Record<string, string> = {
    present: 'present',
    absent: 'absent',
    halfday: 'halfDay',
    leave: 'leave',
    holiday: 'holiday',
    overtime: 'overtime',
    approved: 'approved',
    pending: 'pending',
    rejected: 'rejected',
    draft: 'draft',
    paid: 'paid',
    active: 'active',
    inactive: 'inactive',
    suspended: 'suspended',
    expired: 'expired',
    resolved: 'resolved',
    inreview: 'inReview',
    investigating: 'investigating'
  };
  const key = map[s] || status;
  return getTranslation(lang, key, status);
};

export const translateRole = (role: UserRole | string, lang: LanguageCode = 'en'): string => {
  switch (role) {
    case 'Owner':
      return getTranslation(lang, 'roleOwner', 'Platform Owner');
    case 'Super Admin':
      return getTranslation(lang, 'roleSuperAdmin', 'Super Admin');
    case 'HR Admin':
      return getTranslation(lang, 'roleHrAdmin', 'HR Admin');
    case 'Site Supervisor':
      return getTranslation(lang, 'roleSupervisor', 'Site Supervisor');
    case 'Labor':
      return getTranslation(lang, 'roleLabor', 'Site Laborer');
    default:
      return role;
  }
};

export interface I18nContextType {
  lang: LanguageCode;
  setLang: (lang: LanguageCode) => void;
  t: (key: string, defaultText?: string) => string;
  isRTL: boolean;
  translateStatus: (status: string) => string;
  translateRole: (role: UserRole | string) => string;
}

export const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  setLang: () => {},
  t: (key: string, defaultText?: string) => defaultText || key,
  isRTL: false,
  translateStatus: (status: string) => status,
  translateRole: (role: UserRole | string) => role
});

export const useI18n = (): I18nContextType => useContext(I18nContext);

export const I18nProvider: React.FC<{
  currentLang: LanguageCode;
  onLanguageChange: (lang: LanguageCode) => void;
  children: React.ReactNode;
}> = ({ currentLang, onLanguageChange, children }) => {
  const isRTL = currentLang === 'ar' || currentLang === 'ur';

  useEffect(() => {
    document.documentElement.lang = currentLang;
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    if (isRTL) {
      document.body.classList.add('rtl-layout');
    } else {
      document.body.classList.remove('rtl-layout');
    }
  }, [currentLang, isRTL]);

  const t = (key: string, defaultText?: string) => getTranslation(currentLang, key, defaultText);

  return (
    <I18nContext.Provider
      value={{
        lang: currentLang,
        setLang: onLanguageChange,
        t,
        isRTL,
        translateStatus: (status: string) => translateStatus(status, currentLang),
        translateRole: (role: UserRole | string) => translateRole(role, currentLang)
      }}
    >
      <div dir={isRTL ? 'rtl' : 'ltr'} className={isRTL ? 'font-sans rtl' : 'font-sans'}>
        {children}
      </div>
    </I18nContext.Provider>
  );
};
